export function installHelp() {
  const dialog=document.getElementById('analysisHelp');
  for(const button of document.querySelectorAll('[data-help]')) {
    const topic=topics[button.dataset.help]; if(!topic)throw new Error(`Unknown help: ${button.dataset.help}`);
    button.type='button';button.classList.add('help-icon');button.textContent='?';button.setAttribute('aria-label',`${topic[0]}の説明`);button.setAttribute('aria-haspopup','dialog');
    button.onclick=e=>{e.preventDefault();document.getElementById('analysisHelpTitle').textContent=topic[0];const body=document.getElementById('analysisHelpBody');body.replaceChildren();renderExamples(button.dataset.help,body);for(const [title,text] of topic.slice(1)){const h=document.createElement('h3'),p=document.createElement('p');h.textContent=title;p.textContent=text;body.append(h,p);}dialog.showModal();dialog.scrollTop=0;};
  }
  document.getElementById('closeAnalysisHelp').onclick=()=>dialog.close();
}
